export const currentLang = ref(localStorage.getItem(LANG_KEY) || 'zh')

export function setLang(lang) {
  currentLang.value = lang
  localStorage.setItem(LANG_KEY, lang)
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en'
}

export function t(key, params = {}) {
  const dict = messages[currentLang.value] || messages.en
  let str = dict[key] ?? messages.en[key] ?? key
  for (const [k, v] of Object.entries(params)) {
    str = str.replaceAll(`{${k}}`, String(v))
  }
  return str
}

export function elementLocale() {
  return (messages[currentLang.value] || messages.en).el
}

export function toggleLang() {
  setLang(currentLang.value === 'zh' ? 'en' : 'zh')
}
